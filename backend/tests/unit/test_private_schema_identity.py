"""Sealed auto keys retain generation; ordinary integer fields do not gain it."""

from contextlib import contextmanager
from types import SimpleNamespace

import pytest
from django.contrib.auth.models import Group, User
from django.core.management import call_command
from django.core.management.base import CommandError
from django.db import connection, transaction
from django.db.migrations.recorder import MigrationRecorder

from execution_jobs import preflight, schema_presence
from execution_jobs.models import QueueLock
from tests.unit.test_private_schema_presence import physical_database  # noqa: F401

pytestmark = [pytest.mark.unit, pytest.mark.django_db(transaction=True)]

AUTO_TABLES = ["auth_user", "auth_user_groups", "django_migrations", "access_control_projectmembership"]
ORDINARY_COLUMNS = [
    ("execution_jobs_queuelock", "id"),
    ("auth_user_groups", "user_id"),
    ("execution_jobs_nativejob", "attempts"),
]
CASES = [(table, "id", action) for table in AUTO_TABLES
         for action in ("DROP IDENTITY", "SET GENERATED ALWAYS")]
CASES += [(table, column, "ADD GENERATED BY DEFAULT AS IDENTITY") for table, column in ORDINARY_COLUMNS]


def run(command):
    return call_command("check_job_runtime") if command else preflight.check_runtime()


@pytest.mark.parametrize("command", [False, True])
@pytest.mark.parametrize("table,column,action", CASES)
def test_identity_mismatch_blocks_before_broker(physical_database, monkeypatch, command, table, column, action):
    seed = User.objects.create(username="u", password="retained-password", is_superuser=False)
    history = set(MigrationRecorder(connection).applied_migrations())
    if connection.vendor == "sqlite":
        # Explicit denial references only. SQLite does not implement PostgreSQL
        # identity modes, catalog flags or the ALTER COLUMN operations below.
        @contextmanager
        def catalog():
            rows = [(t, "r", not (t == table and c == column), c)
                    for t, columns in schema_presence.required_schema().items() for c in columns]
            yield SimpleNamespace(execute=lambda *args: None, fetchall=lambda: rows)

        monkeypatch.setattr(schema_presence, "connection", SimpleNamespace(cursor=catalog))
    with transaction.atomic():
        if connection.vendor == "postgresql":
            with connection.cursor() as cursor:
                cursor.execute(f'ALTER TABLE public."{table}" ALTER COLUMN "{column}" {action}')
                cursor.execute("SELECT username,password FROM public.auth_user WHERE id=%s", [seed.pk])
                assert cursor.fetchone() == ("u", "retained-password")
        try:
            expected = CommandError if command else preflight.RuntimeUnavailable
            with pytest.raises(expected, match="^job_schema_invalid$"):
                run(command)
            physical_database.ensure_connection.assert_not_called()
            assert set(MigrationRecorder(connection).applied_migrations()) == history
        finally:
            transaction.set_rollback(True)
    restored = User.objects.get(pk=seed.pk)
    assert restored.username == "u" and restored.password == "retained-password" and restored.is_superuser is False
    assert set(MigrationRecorder(connection).applied_migrations()) == history


@pytest.mark.parametrize("command", [False, True])
@pytest.mark.parametrize("extra", [False, True])
def test_declared_identity_and_ordinary_writes_remain_supported(physical_database, command, extra):
    seed = User.objects.create(username="u", password="retained-password", is_superuser=False)
    history = set(MigrationRecorder(connection).applied_migrations())
    with transaction.atomic():
        with connection.cursor() as cursor:
            if connection.vendor == "postgresql":
                for table in AUTO_TABLES:
                    cursor.execute(f"SELECT a.attidentity FROM pg_catalog.pg_attribute a WHERE a.attrelid OPERATOR(pg_catalog.=) 'public.{table}'::pg_catalog.regclass AND a.attname OPERATOR(pg_catalog.=) 'id'::pg_catalog.name")
                    assert cursor.fetchone() == ("d",)
                for table, column in ORDINARY_COLUMNS:
                    cursor.execute(f"SELECT a.attidentity FROM pg_catalog.pg_attribute a WHERE a.attrelid OPERATOR(pg_catalog.=) 'public.{table}'::pg_catalog.regclass AND a.attname OPERATOR(pg_catalog.=) %s::pg_catalog.name", [column])
                    assert cursor.fetchone() == ("",)
                if extra:
                    cursor.execute("ALTER TABLE public.auth_user ADD COLUMN identity_fixture_extra int GENERATED ALWAYS AS IDENTITY")
            elif extra:
                cursor.execute("ALTER TABLE auth_user ADD COLUMN identity_fixture_extra int")
        result = run(command)
        if not command:
            assert result["migrations"] == "current"
        physical_database.ensure_connection.assert_called_once_with(max_retries=0)
        created = User.objects.create(username="implicit-identity-control", password="supported")
        assert created.pk is not None
        explicit = User.objects.create(pk=30001, username="explicit-identity-control", password="supported")
        assert explicit.pk == 30001
        group = Group.objects.create(name="identity-control")
        seed.groups.add(group)
        assert seed.groups.filter(pk=group.pk).exists()
        lock = QueueLock.objects.create(id=30001)
        assert lock.pk == 30001
        transaction.set_rollback(True)
    assert User.objects.get(pk=seed.pk).password == "retained-password"
    assert not User.objects.filter(username__endswith="identity-control").exists()
    assert not Group.objects.filter(name="identity-control").exists()
    assert not QueueLock.objects.filter(pk=30001).exists()
    assert set(MigrationRecorder(connection).applied_migrations()) == history
